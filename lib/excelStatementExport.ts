import * as XLSX from 'xlsx'

interface ExportStatementOptions {
  fromDate?: string
  toDate?: string
  statusFilter?: string
  generatedBy?: string
}

export function exportOrdersBankStatement(orders: any[], options: ExportStatementOptions = {}) {
  if (!orders || orders.length === 0) {
    throw new Error('No orders available to export for the selected filter')
  }

  const { fromDate, toDate, statusFilter = 'ALL', generatedBy = 'Admin' } = options

  // 1. Calculate Summary Metrics
  const totalOrders = orders.length
  const totalAmount = orders.reduce((sum, o) => sum + (o.totalAmount || 0), 0)
  
  const deliveredOrders = orders.filter(o => o.status === 'DELIVERED')
  const deliveredAmount = deliveredOrders.reduce((sum, o) => sum + (o.totalAmount || 0), 0)
  
  const activeOrders = orders.filter(o => !['DELIVERED', 'RETURNED', 'CANCELLED'].includes(o.status))
  
  const codOrders = orders.filter(o => o.paymentMethod === 'CASH_ON_DELIVERY')
  const codAmount = codOrders.reduce((sum, o) => sum + (o.totalAmount || 0), 0)
  
  const upiOrders = orders.filter(o => o.paymentMethod === 'UPI' || o.paymentMethod === 'ONLINE')
  const upiAmount = upiOrders.reduce((sum, o) => sum + (o.totalAmount || 0), 0)
  
  const creditOrders = orders.filter(o => o.paymentMethod === 'CREDIT_ACCOUNT')
  const creditAmount = creditOrders.reduce((sum, o) => sum + (o.totalAmount || 0), 0)

  const totalPackets = orders.reduce((sum, o) => {
    const itemsSum = o.items?.reduce((iSum: number, it: any) => iSum + (it.quantity || 0), 0) || 0
    return sum + itemsSum
  }, 0)

  const dateRangeStr = fromDate && toDate 
    ? `${fromDate} to ${toDate}`
    : fromDate 
      ? `From ${fromDate}`
      : toDate 
        ? `Until ${toDate}`
        : 'All Available Records'

  const generatedTimeStr = new Date().toLocaleString('en-IN', {
    timeZone: 'Asia/Kolkata',
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true
  })

  // 2. Build 2D Sheet Rows
  const sheetData: any[][] = [
    // Header Block (Bank Statement Format)
    ['ANMOL ENTERPRISES'],
    ['Official McCain Foods India Distributor & Cold-Chain Logistics Hub'],
    ['ORDERS & DISPATCH ACCOUNT STATEMENT'],
    [`Statement Period: ${dateRangeStr}`, '', '', `Generated On: ${generatedTimeStr}`],
    [`Generated By: ${generatedBy}`, '', '', `Active Filter: ${statusFilter}`],
    [], // Blank separator

    // Financial & Operational Summary Box
    ['EXECUTIVE FINANCIAL & DISPATCH SUMMARY', '', '', '', ''],
    ['Total Orders Registered:', totalOrders, '', 'Gross Turnover (₹):', totalAmount],
    ['Delivered Orders:', deliveredOrders.length, '', 'Delivered Turnover (₹):', deliveredAmount],
    ['Active / In-Pipeline Orders:', activeOrders.length, '', 'Total Packets Dispatched:', totalPackets],
    ['Cash on Delivery (COD) (₹):', codAmount, '', 'Online / UPI Paid (₹):', upiAmount],
    ['B2B Store Credit (₹):', creditAmount, '', 'Returns / Cancelled:', orders.filter(o => ['RETURNED', 'CANCELLED'].includes(o.status)).length],
    [], // Blank separator

    // Transaction Statement Ledger Table Header
    [
      'Sr.',
      'Date & Time',
      'Order / Bill #',
      'Customer / Business Name',
      'Contact Phone',
      'Delivery Address / Area',
      'Items Ordered (Product & Pack Details)',
      'Total Pkts',
      'Payment Mode',
      'Payment Status',
      'Dispatch Status',
      'Order Amount (₹)'
    ]
  ]

  // 3. Add Order Ledger Rows
  orders.forEach((order, index) => {
    const orderDateStr = order.createdAt 
      ? new Date(order.createdAt).toLocaleString('en-IN', {
          timeZone: 'Asia/Kolkata',
          day: '2-digit',
          month: 'short',
          year: 'numeric',
          hour: '2-digit',
          minute: '2-digit',
          hour12: true
        })
      : ''

    const customerDisplay = order.businessName 
      ? `${order.businessName} (${order.guestName || order.user?.name || 'Direct'})` 
      : (order.guestName || order.user?.name || 'Walk-in Retail')

    const contactPhone = order.guestPhone || order.user?.phone || 'N/A'
    const address = order.deliveryAddress || 'Store Counter Pickup'
    
    const itemsDescription = order.items?.map((it: any) => 
      `${it.quantity}x ${it.productName} (${it.packagingType})`
    ).join('; ') || 'No Items'

    const orderPackets = order.items?.reduce((sum: number, it: any) => sum + (it.quantity || 0), 0) || 0

    const paymentMethodLabel = order.paymentMethod === 'CASH_ON_DELIVERY' 
      ? 'Cash (COD)' 
      : order.paymentMethod === 'CREDIT_ACCOUNT' 
        ? 'B2B Credit' 
        : 'UPI / Online'

    sheetData.push([
      index + 1,
      orderDateStr,
      order.orderNumber || 'N/A',
      customerDisplay,
      contactPhone,
      address,
      itemsDescription,
      orderPackets,
      paymentMethodLabel,
      order.paymentStatus || 'PENDING',
      order.status || 'PENDING',
      order.totalAmount || 0
    ])
  })

  // 4. Grand Total Row
  sheetData.push([
    'TOTAL',
    '',
    '',
    '',
    '',
    '',
    `Total Transactions: ${totalOrders}`,
    totalPackets,
    '',
    '',
    '',
    totalAmount
  ])

  // 5. Convert to Worksheet
  const worksheet = XLSX.utils.aoa_to_sheet(sheetData)

  // 6. Set Proportional Column Widths
  worksheet['!cols'] = [
    { wch: 6 },  // Sr.
    { wch: 22 }, // Date & Time
    { wch: 20 }, // Order #
    { wch: 30 }, // Customer Name
    { wch: 15 }, // Phone
    { wch: 32 }, // Address
    { wch: 45 }, // Items
    { wch: 12 }, // Total Pkts
    { wch: 16 }, // Payment Mode
    { wch: 14 }, // Payment Status
    { wch: 18 }, // Dispatch Status
    { wch: 16 }, // Amount
  ]

  // 7. Create Workbook & Trigger Download
  const workbook = XLSX.utils.book_new()
  XLSX.utils.book_append_sheet(workbook, worksheet, 'Orders Statement')

  const filenameDate = new Date().toISOString().slice(0, 10)
  XLSX.writeFile(workbook, `Anmol_Enterprises_Statement_${filenameDate}.xlsx`)
}
